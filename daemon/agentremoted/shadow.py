"""Snapshots of a session's folder, taken *beside* it.

`changes.py` answers "what is different from the last commit". That is the
wrong question for a long session: by the tenth turn it is ten turns of work
plus whatever you edited yourself, and in a folder that is not a repository
at all it has no answer.

This module gives the other scope — "what changed since this turn started" —
without a repository and without touching the one that is there:

    git init --bare ~/.agentremoted/shadow/<key>
    git --git-dir=<that> --work-tree=<cwd> add -A
    git --git-dir=<that> --work-tree=<cwd> write-tree   -> a tree object

A tree id is the whole marker. Two of them diff like any two commits
(`git diff <t1> <t2>`), so the full diff machinery — renames, binary
detection, numstat — comes for free.

Three properties make this safe to run on someone's working folder:

* It writes **nothing** into the work tree. The index, the objects and the
  config all live in the shadow directory.
* It never touches the project's own git: different `--git-dir`, so its
  index is never locked, its HEAD never moves, its stash and reflog stay as
  they are. `git status` in that folder after a snapshot is byte-identical.
* There are **no commits**, so there is no author identity to invent and
  nothing to sign. `write-tree` needs neither.

What it costs: one `add -A` walk per turn. On this repository (390 files)
that is ~0.5 s cold and far less warm, because the shadow index keeps stat
information between turns. The walk honours the work tree's own `.gitignore`
files — git reads those from the work tree, not from the git dir — so in a
real repository the project's own idea of noise is inherited for free. In a
folder that is not a repository there is usually no `.gitignore`, so a
built-in list of generated directories stands in for one.
"""

import hashlib
import json
import os
import subprocess
import threading
import time

from . import config

# A snapshot of a huge tree is not worth waiting for; the folder is marked
# and left alone for a while rather than retried on every turn.
SNAPSHOT_TIMEOUT = 20
# What a turn may wait for its own mark. The walk has to finish before the
# agent starts editing, so this is on the critical path of every message;
# a folder that cannot be walked in this long is better left unmarked.
TURN_BUDGET = 6
WRITE_TREE_TIMEOUT = 20
BLOCKED_FOR = 600.0

# Stands in for .gitignore in a folder that is not a repository. Only
# directories that are generated by definition: anything hand-written that
# happens to sit in one of these is better shown than silently dropped.
DEFAULT_EXCLUDES = """\
# Written by agentremoted. Stands in for a .gitignore this folder does not
# have, so a snapshot does not walk build output.
.DS_Store
node_modules/
bower_components/
.venv/
venv/
__pycache__/
*.pyc
.mypy_cache/
.pytest_cache/
.tox/
.gradle/
.kotlin/
build/
target/
out/
dist/
.pio/
.next/
.nuxt/
.cache/
DerivedData/
Pods/
vendor/
.terraform/
*.o
*.a
*.so
*.class
"""

_SAFE = ["-c", "core.fsmonitor=false", "-c", "core.quotepath=false",
         "-c", "diff.external=", "-c", "color.ui=false",
         "-c", "gc.auto=0"]

_lock = threading.Lock()
_blocked = {}          # cwd -> time it may be tried again


def _shadow_root():
    return os.path.join(str(config.CONFIG_DIR), "shadow")


def _key(cwd):
    real = os.path.realpath(cwd)
    return hashlib.sha1(real.encode("utf-8", "replace")).hexdigest()[:16]


def _git_dir(cwd):
    return os.path.join(_shadow_root(), _key(cwd))


def _run(cwd, git_dir, args, timeout):
    """(returncode, stdout bytes). -1 could not run, -2 ran out of time."""
    env = dict(os.environ)
    env["GIT_TERMINAL_PROMPT"] = "0"
    env["LC_ALL"] = "C"
    # Belt and braces: the explicit flags below already win, but a stray
    # GIT_DIR / GIT_INDEX_FILE in the daemon's environment would be read
    # before them by some git versions.
    for leak in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE",
                 "GIT_OBJECT_DIRECTORY"):
        env.pop(leak, None)
    cmd = ["git", "--git-dir", git_dir, "--work-tree", cwd] + _SAFE + args
    try:
        out = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True,
                             timeout=timeout)
    except subprocess.TimeoutExpired:
        return -2, b""
    except (OSError, subprocess.SubprocessError):
        return -1, b""
    return out.returncode, out.stdout


def _is_repo(cwd):
    try:
        out = subprocess.run(["git", "rev-parse", "--is-inside-work-tree"],
                             cwd=cwd, capture_output=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return False
    return out.returncode == 0 and out.stdout.strip() == b"true"


def _too_big_to_be_a_project(cwd):
    """Refuse the folders where `add -A` means "walk everything you own"."""
    real = os.path.realpath(cwd)
    if real in ("/", os.path.realpath(os.path.expanduser("~"))):
        return True
    # One level under / (e.g. /Users, /Volumes) is never a project either.
    parent = os.path.dirname(real)
    return parent == "/" and real != "/"


def too_big(cwd):
    """Home, / or one level under /: never snapshotted (see below)."""
    return _too_big_to_be_a_project(cwd)


def unwalkable(cwd):
    """Whether a snapshot of `cwd` is refused or recently ran out of time."""
    if _too_big_to_be_a_project(cwd):
        return True
    with _lock:
        return _blocked.get(cwd, 0.0) > time.time() or \
            _blocked.get(os.path.realpath(cwd), 0.0) > time.time()


def _ensure(cwd):
    """The shadow git dir for `cwd`, created on first use. "" when it can't be."""
    git_dir = _git_dir(cwd)
    if os.path.isdir(os.path.join(git_dir, "objects")):
        return git_dir
    try:
        os.makedirs(git_dir, exist_ok=True)
        os.chmod(_shadow_root(), 0o700)
    except OSError:
        return ""
    try:
        out = subprocess.run(["git", "init", "--bare", "-q", git_dir],
                             capture_output=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return ""
    if out.returncode != 0:
        return ""
    # A bare repository with an explicit --work-tree is the long-standing
    # "dotfiles repo" arrangement; core.bare has to say so or git refuses to
    # look at a work tree at all.
    for key, value in (("core.bare", "false"),
                       ("gc.auto", "0"),
                       ("core.logAllRefUpdates", "false")):
        subprocess.run(["git", "--git-dir", git_dir, "config", key, value],
                       capture_output=True, timeout=10)
    try:
        # Written once, at creation: a folder that gains a .gitignore later
        # gets it honoured anyway, and one that loses its repository keeps
        # whatever it had.
        if not _is_repo(cwd):
            with open(os.path.join(git_dir, "info", "exclude"), "w") as fh:
                fh.write(DEFAULT_EXCLUDES)
        # For the human who finds this directory and wonders what it is.
        with open(os.path.join(git_dir, "agentremoted-cwd"), "w") as fh:
            fh.write(os.path.realpath(cwd) + "\n")
    except OSError:
        pass
    return git_dir


def _marks_path(git_dir):
    return os.path.join(git_dir, "agentremoted-turns.json")


def _read_marks(git_dir):
    try:
        with open(_marks_path(git_dir)) as fh:
            data = json.load(fh)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def _write_marks(git_dir, data):
    tmp = _marks_path(git_dir) + ".tmp"
    try:
        with open(tmp, "w") as fh:
            json.dump(data, fh)
        os.replace(tmp, _marks_path(git_dir))
    except OSError:
        try:
            os.unlink(tmp)
        except OSError:
            pass


def available():
    """Whether snapshots can be taken at all (git on PATH)."""
    try:
        return subprocess.run(["git", "--version"], capture_output=True,
                              timeout=5).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def snapshot(cwd, budget=SNAPSHOT_TIMEOUT):
    """Stage everything under `cwd` and return the tree id. "" on failure.

    Nothing in the work tree is written or moved. Safe to call from any
    thread; one folder at a time, because a second `add -A` would queue on
    the shadow index lock anyway.

    `budget` is how long the walk may take. The turn path passes a short one
    and gives up rather than hold up the agent; reading the diff afterwards
    can afford to wait longer.
    """
    if not cwd or not os.path.isdir(cwd) or _too_big_to_be_a_project(cwd):
        return ""
    with _lock:
        until = _blocked.get(cwd, 0.0)
        if until > time.time():
            return ""
    git_dir = _ensure(cwd)
    if not git_dir:
        return ""
    code, _out = _run(cwd, git_dir, ["add", "-A", "--ignore-errors"], budget)
    if code == -2:
        # Too slow once is enough: a folder this size will be too slow again.
        with _lock:
            _blocked[cwd] = time.time() + BLOCKED_FOR
        return ""
    if code not in (0, 1):
        return ""
    code, out = _run(cwd, git_dir, ["write-tree"], WRITE_TREE_TIMEOUT)
    if code != 0:
        return ""
    tree = out.decode("ascii", "replace").strip()
    return tree if len(tree) == 40 and all(
        c in "0123456789abcdef" for c in tree) else ""


def mark_turn(cwd, budget=TURN_BUDGET):
    """Record where this folder stood as a turn begins.

    Called on the way into a turn and allowed to fail: a snapshot that does
    not happen costs the "This turn" view, nothing else. It runs *before*
    the agent does, because a mark taken afterwards is not a mark.
    """
    tree = snapshot(cwd, budget=budget)
    if not tree:
        return ""
    git_dir = _git_dir(cwd)
    marks = _read_marks(git_dir)
    now = time.time()
    current = marks.get("current") or {}
    # The turn that just ended becomes the previous one, so "this turn" and
    # "the turn before it" are both answerable.
    if current.get("tree") and current.get("tree") != tree:
        marks["previous"] = current
    marks["current"] = {"tree": tree, "at": now}
    _write_marks(git_dir, marks)
    return tree


def base_for(cwd):
    """{"tree", "at"} recorded at the start of the last turn, or None."""
    if not cwd or _too_big_to_be_a_project(cwd):
        return None
    git_dir = _git_dir(cwd)
    if not os.path.isdir(git_dir):
        return None
    mark = _read_marks(git_dir).get("current")
    if isinstance(mark, dict) and mark.get("tree"):
        return mark
    return None


def diff_args(cwd, base_tree, args):
    """Run a git diff in the shadow repo; (returncode, stdout bytes)."""
    git_dir = _git_dir(cwd)
    if not os.path.isdir(git_dir):
        return -1, b""
    return _run(cwd, git_dir, ["diff"] + args, SNAPSHOT_TIMEOUT)


def diff_popen(cwd, args):
    """Popen for a shadow-repo diff, for the capped streaming reader."""
    git_dir = _git_dir(cwd)
    if not os.path.isdir(git_dir):
        return None
    env = dict(os.environ)
    env["GIT_TERMINAL_PROMPT"] = "0"
    env["LC_ALL"] = "C"
    for leak in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE",
                 "GIT_OBJECT_DIRECTORY"):
        env.pop(leak, None)
    cmd = (["git", "--git-dir", git_dir, "--work-tree", cwd]
           + _SAFE + ["diff"] + args)
    try:
        return subprocess.Popen(cmd, cwd=cwd, env=env,
                                stdout=subprocess.PIPE,
                                stderr=subprocess.DEVNULL)
    except OSError:
        return None


def forget(cwd):
    """Drop the snapshots for one folder (its shadow directory)."""
    import shutil
    git_dir = _git_dir(cwd)
    if os.path.isdir(git_dir):
        shutil.rmtree(git_dir, ignore_errors=True)
